#!/usr/bin/env python3
"""Embed a Vite build (web/dist) into a C++ translation unit.

The generated file contains one byte array per asset plus a sorted manifest
table consumed by WebAssetIndex. It is deterministic: files are sorted by URL
path, no timestamps are written, and the manifest digest is derived only from
the asset paths and content hashes.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
from pathlib import Path

MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".map": "application/json; charset=utf-8",
    ".webmanifest": "application/manifest+json",
    ".txt": "text/plain; charset=utf-8",
    ".xml": "application/xml; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".ttf": "font/ttf",
    ".wasm": "application/wasm",
}

COMPRESSIBLE_PREFIXES = (
    "text/",
    "application/json",
    "application/manifest+json",
    "application/xml",
    "image/svg+xml",
)


def fail(message: str) -> "NoReturn":
    print(f"[web-assets] error: {message}", file=sys.stderr)
    raise SystemExit(1)


def content_type_for(path: Path) -> str:
    suffix = path.suffix.lower()
    if suffix not in MIME_TYPES:
        fail(f"no MIME mapping for '{path}' (suffix '{suffix or '<none>'}'); update scripts/gen_web_assets.py")
    return MIME_TYPES[suffix]


def cpp_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def emit_byte_array(index: int, data: bytes) -> str:
    if not data:
        # A zero-length C++ array is ill-formed; the manifest still advertises
        # length 0, so the dummy byte is never served.
        return f"constexpr unsigned char kAsset{index}[1] = {{0x00}};\n"
    lines = [f"constexpr unsigned char kAsset{index}[] = {{"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def render(input_dir: Path, assets: list[tuple[str, Path, bytes, str, str, bool]], manifest_hash: str) -> str:
    out: list[str] = []
    out.append("// Generated by scripts/gen_web_assets.py. Do not edit by hand.\n")
    out.append('#include "service/web/web_asset.hpp"\n\n')
    out.append("#include <cstddef>\n")
    out.append("#include <iterator>\n")
    out.append("#include <span>\n")
    out.append("#include <string_view>\n\n")
    out.append("namespace eugraph {\nnamespace service {\nnamespace web {\nnamespace {\n\n")

    for index, (_url, _path, data, _mime, _etag, _compressible) in enumerate(assets):
        out.append(emit_byte_array(index, data))
        out.append("\n")

    out.append("const WebAsset kAssets[] = {\n")
    for index, (url, _path, data, mime, etag, compressible) in enumerate(assets):
        length = len(data)
        out.append(
            "    {"
            + cpp_string(url)
            + ", "
            + cpp_string(mime)
            + ", "
            + cpp_string(etag)
            + f", std::string_view(reinterpret_cast<const char*>(kAsset{index}), {length})"
            + (", true" if compressible else ", false")
            + "},\n"
        )
    out.append("};\n\n")
    out.append("} // namespace\n\n")
    out.append("std::span<const WebAsset> embeddedWebAssets() {\n")
    out.append("    return {kAssets, std::size(kAssets)};\n")
    out.append("}\n\n")
    out.append("std::string_view embeddedAssetsHash() {\n")
    out.append(f"    return {cpp_string(manifest_hash)};\n")
    out.append("}\n\n")
    out.append("} // namespace web\n} // namespace service\n} // namespace eugraph\n")
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path, help="Vite output directory (web/dist)")
    parser.add_argument("--output", required=True, type=Path, help="C++ source file to write")
    args = parser.parse_args()

    input_dir: Path = args.input.resolve()
    if not input_dir.is_dir():
        fail(f"input directory '{input_dir}' does not exist")

    index_html = input_dir / "index.html"
    if not index_html.is_file():
        fail(f"'{index_html}' is missing; build the frontend first (scripts/build-web.sh)")

    files = sorted(
        path for path in input_dir.rglob("*") if path.is_file() and not path.name.startswith(".")
    )
    if not files:
        fail(f"input directory '{input_dir}' contains no files")

    assets: list[tuple[str, Path, bytes, str, str, bool]] = []
    manifest = hashlib.sha256()
    seen: set[str] = set()
    total_bytes = 0

    for path in files:
        relative = path.relative_to(input_dir).as_posix()
        url = "/" + relative
        if url in seen:
            fail(f"duplicate asset path '{url}'")
        seen.add(url)

        data = path.read_bytes()
        total_bytes += len(data)
        mime = content_type_for(path)
        etag = hashlib.sha256(data).hexdigest()
        compressible = mime.startswith(COMPRESSIBLE_PREFIXES)

        manifest.update(url.encode("utf-8"))
        manifest.update(b"\0")
        manifest.update(etag.encode("ascii"))
        manifest.update(b"\n")
        assets.append((url, path, data, mime, etag, compressible))

    assets.sort(key=lambda item: item[0])
    manifest_hash = manifest.hexdigest()

    output_path: Path = args.output
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render(input_dir, assets, manifest_hash), encoding="utf-8")

    print(
        f"[web-assets] {len(assets)} files, {total_bytes} bytes raw, "
        f"manifest {manifest_hash[:16]} -> {output_path}"
    )


if __name__ == "__main__":
    main()
